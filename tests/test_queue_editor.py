def _declared_flags(source):
    """Every long/short option string passed to parser.add_argument()."""
    flags = set()
    for node in ast.walk(ast.parse(source)):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        if not (isinstance(func, ast.Attribute) and func.attr == "add_argument"):
            continue
        for arg in node.args:
            if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
                flags.add(arg.value)
    return flags


class TestQueueAddCallsTheArchGuard:
    def test_core_add_queue_checks_arch_before_writing_the_config(self):
        """The architecture guard is only useful if it runs before the
        edit is persisted -- _save_cluster_config now writes the live
        cluster's only config file and mirrors it to the shared store.

        manage_pcluster_queue.py's own _do_add no longer contains this logic
        -- it now delegates to core_add_queue in pcluster_core.py, which is
        where the ordering guarantee actually lives now."""
        fn = next(
            n for n in ast.walk(ast.parse(_core_source()))
            if isinstance(n, ast.FunctionDef) and n.name == "core_add_queue"
        )
        called = [
            n.func.id for n in ast.walk(fn)
            if isinstance(n, ast.Call) and isinstance(n.func, ast.Name)
        ]
        assert "_check_queue_arch_matches_cluster" in called, (
            "core_add_queue does not call the architecture guard"
        )
        assert called.index("_check_queue_arch_matches_cluster") < called.index(
            "_save_cluster_config"
        ), "the arch guard must run before the config is rewritten"


class TestQueueCliFlagNames:
    def test_error_messages_name_only_real_flags(self):
        """The messages named `-E/--ec2_instance_type`, `--queue_name`, and
        `-T/--queue_type` — those are argparse `dest=` names, not flags. A user
        who copied the flag out of the error got "unrecognized arguments" on the
        retry."""
        source = _cli_source()
        declared = _declared_flags(source)
        assert declared, "no add_argument flags parsed out of manage_pcluster_queue.py"

        # Only this script's own diagnostics. Reminder text also prints real
        # `pcluster update-cluster` invocations, whose flags belong to that CLI.
        cited = set()
        for node in ast.walk(ast.parse(source)):
            if not isinstance(node, ast.Call):
                continue
            func = node.func
            is_error = (
                isinstance(func, ast.Attribute) and func.attr in ("exit", "error")
            ) or (isinstance(func, ast.Name) and func.id == "SystemExit")
            if not is_error:
                continue
            # Join each message's segments first: an f-string splits into
            # Constants around every {placeholder}, so filtering per-segment
            # would strip the "pcluster " context off a trailing " --region ".
            text = " ".join(
                arg.value for arg in ast.walk(node)
                if isinstance(arg, ast.Constant) and isinstance(arg.value, str)
            )
            # Some messages embed a `pcluster ...` command to run; those flags
            # belong to the ParallelCluster CLI, not to this script.
            if "pcluster " in text:
                continue
            cited.update(re.findall(r"--[a-z][a-z_0-9-]*", text))
        assert cited, "no flags cited in any error message — guard would be vacuous"

        bogus = sorted(f for f in cited if f not in declared)
        assert not bogus, (
            f"error/help text cites flags argparse does not accept: {bogus}\n"
            f"declared: {sorted(f for f in declared if f.startswith('--'))}"
        )

    def test_queue_type_is_required_only_for_add(self):
        """_do_remove never reads args.queue_type, but main() used to reject a
        remove without -T, forcing the user to state a queue type that has no
        effect on the operation."""
        source = _cli_source()
        tree = ast.parse(source)

        remove_fn = next(
            n for n in ast.walk(tree)
            if isinstance(n, ast.FunctionDef) and n.name == "_do_remove"
        )
        reads_type = any(
            isinstance(n, ast.Attribute) and n.attr == "queue_type"
            for n in ast.walk(remove_fn)
        )
        assert not reads_type, (
            "_do_remove now reads queue_type; if that is intentional, main() must "
            "require -T for remove again and this test should be updated"
        )

        guard = re.search(r"if args\.action[^\n]*not args\.queue_type", source)
        assert guard, "the -T/--type requirement guard is gone from main()"
        assert "remove" not in guard.group(0), (
            f"main() still requires -T for remove: {guard.group(0)!r}"
        )
