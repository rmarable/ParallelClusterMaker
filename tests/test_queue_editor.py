class TestCheckQueueArchMatchesCluster:
    """make_pcluster.py hard-fails on mixed head/compute architecture at build
    time, but nothing re-checked it when adding a queue to a live cluster, so
    `add` could bolt a Graviton queue onto an x86 cluster. PCluster accepts that
    config; the breakage surfaces later and indirectly — one Os setting is
    architecture-specific, and head-node-built software (Spack, the benchmark
    suite, anything with -march=native) cannot execute on a foreign node."""

    def test_arm_queue_on_arm_cluster_is_allowed(self):
        cfg = _make_yaml().load(SAMPLE_CONFIG)
        _check_queue_arch_matches_cluster(cfg, ["c7g.4xlarge"])

    def test_x86_queue_on_x86_cluster_is_allowed(self):
        cfg = _make_yaml().load(SAMPLE_CONFIG.replace("c8g.", "c5."))
        _check_queue_arch_matches_cluster(cfg, ["c5.4xlarge"])

    def test_x86_queue_on_arm_cluster_is_rejected(self):
        cfg = _make_yaml().load(SAMPLE_CONFIG)
        with pytest.raises(PClusterMakerError) as exc:
            _check_queue_arch_matches_cluster(cfg, ["c5.4xlarge"])
        msg = str(exc.value)
        assert "does not match this cluster" in msg
        assert "arm64" in msg and "x86_64" in msg
        assert "c5.4xlarge" in msg, "the error must name the rejected instance types"

    def test_arm_queue_on_x86_cluster_is_rejected(self):
        cfg = _make_yaml().load(SAMPLE_CONFIG.replace("c8g.", "c5."))
        with pytest.raises(PClusterMakerError) as exc:
            _check_queue_arch_matches_cluster(cfg, ["c7g.4xlarge"])
        assert "does not match this cluster" in str(exc.value)

    def test_indeterminate_cluster_arch_does_not_block(self):
        cfg = _make_yaml().load(SAMPLE_CONFIG.replace("c8g.xlarge", "c5.xlarge"))
        _check_queue_arch_matches_cluster(cfg, ["c7g.4xlarge"])
        _check_queue_arch_matches_cluster(cfg, ["c5.4xlarge"])

    def test_gpu_queue_arch_is_checked_too(self):
        """g5g is the Graviton GPU family; g5 is x86. Adding g5 to an ARM
        cluster is the same mismatch as any CPU queue."""
        cfg = _make_yaml().load(SAMPLE_CONFIG)
        with pytest.raises(PClusterMakerError, match="does not match this cluster"):
            _check_queue_arch_matches_cluster(cfg, ["g5.2xlarge"])


