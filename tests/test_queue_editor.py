class TestValidateQueueName:
    def test_valid_name(self):
        _validate_queue_name("compute-spot")

    def test_valid_short(self):
        _validate_queue_name("q1")

    def test_consecutive_hyphens(self):
        with pytest.raises(PClusterMakerError, match="consecutive hyphens"):
            _validate_queue_name("compute--spot")

    def test_trailing_hyphen(self):
        with pytest.raises(PClusterMakerError, match="invalid queue name"):
            _validate_queue_name("compute-")

    def test_uppercase(self):
        with pytest.raises(PClusterMakerError, match="invalid queue name"):
            _validate_queue_name("Compute")

    # QUEUE_NAME_MAX_LENGTH is 16, but the character-class regex independently
    # caps names at 25, so a 26-char name is rejected either way and proves
    # nothing about the length check. Exercise the boundary itself.
    def test_at_length_limit_accepted(self):
        _validate_queue_name("a" * QUEUE_NAME_MAX_LENGTH)

    def test_one_over_length_limit_rejected(self):
        with pytest.raises(PClusterMakerError, match="the limit is") as exc:
            _validate_queue_name("a" * (QUEUE_NAME_MAX_LENGTH + 1))
        assert "compute resource name" in str(exc.value)

    def test_too_long(self):
        with pytest.raises(PClusterMakerError, match="the limit is"):
            _validate_queue_name("a" * 26)

    def test_underscore_rejected(self):
        with pytest.raises(PClusterMakerError, match="invalid queue name"):
            _validate_queue_name("compute_spot")

    def test_default_is_reserved(self):
        """PCluster's NameValidator has an explicit `re.match("^default$", name)`
        rejection. Accepting it locally means the failure surfaces from
        update-cluster after the compute fleet is already stopped."""
        with pytest.raises(PClusterMakerError, match="reserved"):
            _validate_queue_name("default")

    def test_default_substring_still_allowed(self):
        _validate_queue_name("defaults")
        _validate_queue_name("my-default")

    def test_queue_name_ceiling_leaves_room_for_resource_suffix(self):
        """The derived compute resource name is queue_name + "-resource" and
        PCluster applies the same 25-char NameValidator to it. A queue name that
        passes but whose resource name does not is rejected at update time."""
        assert QUEUE_NAME_MAX_LENGTH == PCLUSTER_NAME_MAX_LENGTH - len(COMPUTE_RESOURCE_SUFFIX)
        longest = "a" * QUEUE_NAME_MAX_LENGTH
        _validate_queue_name(longest)
        assert len(longest + COMPUTE_RESOURCE_SUFFIX) <= PCLUSTER_NAME_MAX_LENGTH
        with pytest.raises(PClusterMakerError, match="compute resource"):
            _validate_queue_name("a" * (QUEUE_NAME_MAX_LENGTH + 1))

    def test_autogenerated_default_name_fits(self):
        """The auto-generated name is f"{queue_type}-{ts}"; with the old
        %Y%m%d-%H%M stamp "compute-20260725-1430" (21 chars) yielded a 30-char
        resource name and every auto-named queue failed at update time."""
        from datetime import datetime
        ts = datetime(2026, 7, 25, 14, 30).strftime("%m%d%H%M")
        for queue_type in ("compute", "gpu"):
            name = f"{queue_type}-{ts}"
            _validate_queue_name(name)
            assert len(name + COMPUTE_RESOURCE_SUFFIX) <= PCLUSTER_NAME_MAX_LENGTH


