class TestRoundTrip:
    def test_add_and_remove_queue_is_lossless(self, tmp_path):
        config_file = tmp_path / "config.mycluster"
        config_file.write_text(SAMPLE_CONFIG)

        yaml = _make_yaml()

        with open(str(config_file)) as fh:
            config = yaml.load(fh)

        new_queue = {
            "Name": "spot-extra",
            "CapacityType": "SPOT",
            "Networking": {"SubnetIds": ["subnet-0abc123"]},
            "ComputeResources": [
                {
                    "Name": "spot-extra-resource",
                    "Instances": [{"InstanceType": "c8g.4xlarge"}],
                    "MinCount": 0,
                    "MaxCount": 4,
                }
            ],
        }
        config["Scheduling"]["SlurmQueues"].append(new_queue)
        _write_cluster_config(str(config_file), config)

        with open(str(config_file)) as fh:
            config2 = yaml.load(fh)

        queues = config2["Scheduling"]["SlurmQueues"]
        config2["Scheduling"]["SlurmQueues"] = [q for q in queues if q["Name"] != "spot-extra"]
        _write_cluster_config(str(config_file), config2)

        final_text = config_file.read_text()
        assert final_text == SAMPLE_CONFIG

    def test_long_scalars_are_not_reflowed(self, tmp_path):
        """ruamel folds at 80 columns by default, so any long value containing
        spaces — a Tags value, a description, a multi-word comment — comes back
        as a multi-line continuation. That is a spurious diff on lines this tool
        never edited, and the fold changes the emitted scalar's whitespace."""
        long_value = (
            "Managed by ParallelClusterMaker for the mycluster HPC cluster "
            "owned by the research computing group in us-east-2"
        )
        assert len(long_value) > 80
        config_file = tmp_path / "config.mycluster"
        config_file.write_text(SAMPLE_CONFIG)

        yaml = _make_yaml()
        with open(str(config_file)) as fh:
            config = yaml.load(fh)
        config["Tags"] = [{"Key": "Purpose", "Value": long_value}]
        _write_cluster_config(str(config_file), config)

        text = config_file.read_text()
        assert long_value in text, "long scalar was folded across lines"

    def test_previous_config_is_backed_up(self, tmp_path):
        """This file is the only copy of a live cluster's configuration. A
        removal the operator wants back, or a rewrite that is valid YAML but
        wrong, is otherwise unrecoverable without a cluster rebuild."""
        config_file = tmp_path / "config.mycluster"
        config_file.write_text(SAMPLE_CONFIG)
        backup = tmp_path / "config.mycluster.bak"
        assert not backup.exists()

        yaml = _make_yaml()
        with open(str(config_file)) as fh:
            config = yaml.load(fh)
        config["Scheduling"]["SlurmQueues"] = [
            q for q in config["Scheduling"]["SlurmQueues"] if q["Name"] != "compute"
        ]
        _write_cluster_config(str(config_file), config)

        assert backup.exists()
        assert backup.read_text() == SAMPLE_CONFIG
        assert "compute" not in config_file.read_text()

    def test_backup_is_skipped_when_no_prior_config(self, tmp_path):
        config_file = tmp_path / "config.newcluster"
        yaml = _make_yaml()
        _write_cluster_config(str(config_file), yaml.load(SAMPLE_CONFIG))
        assert config_file.exists()
        assert not (tmp_path / "config.newcluster.bak").exists()


