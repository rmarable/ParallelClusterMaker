class TestValidateInstanceTypes:
    def test_valid_compute_list(self):
        result = _validate_instance_types("c8g.2xlarge,c7g.2xlarge", require_gpu=False)
        assert isinstance(result, list)
        assert "c8g.2xlarge" in result
        assert "c7g.2xlarge" in result

    # These two are mirror images of each other: inverting the require_gpu
    # conditions in the validator leaves both green under a bare raises(),
    # because each still exits — just down the wrong branch with the wrong
    # advice. Pin the direction of the complaint.
    def test_gpu_rejected_for_compute(self):
        with pytest.raises(PClusterMakerError) as exc:
            _validate_instance_types("g5.2xlarge", require_gpu=False)
        assert "is a GPU instance but --gpu was not specified" in str(exc.value)

    def test_non_gpu_rejected_for_gpu(self):
        with pytest.raises(PClusterMakerError) as exc:
            _validate_instance_types("c5.2xlarge", require_gpu=True)
        assert "is not a GPU instance but --gpu was specified" in str(exc.value)

    def test_valid_gpu(self):
        result = _validate_instance_types("p3.2xlarge", require_gpu=True)
        assert isinstance(result, list)
        assert "p3.2xlarge" in result

    def test_mixed_arch_rejected(self):
        with pytest.raises(PClusterMakerError) as exc:
            _validate_instance_types("c5.2xlarge,c8g.2xlarge", require_gpu=False)
        msg = str(exc.value)
        assert "mixed CPU architectures" in msg
        # The two buckets must not be swapped: c8g is the ARM half.
        assert "ARM: ['c8g.2xlarge']" in msg
        assert "x86: ['c5.2xlarge']" in msg

    def test_unknown_instance_warns_not_aborts(self, capsys):
        result = _validate_instance_types("r99.99xlarge", require_gpu=False)
        assert isinstance(result, list)
        assert "r99.99xlarge" in result
        captured = capsys.readouterr()
        assert "WARNING" in captured.out

    def test_deduplication(self):
        result = _validate_instance_types("c8g.2xlarge,c8g.2xlarge", require_gpu=False)
        assert len(result) == 1

    def test_empty_raises(self):
        with pytest.raises(PClusterMakerError, match="no instance types provided"):
            _validate_instance_types("", require_gpu=False)

    def test_yaml_injection_payload_rejected(self):
        payload = (
            "c6g.xlarge\nIam:\n  AdditionalIamPolicies:\n"
            "    - Policy: arn:aws:iam::aws:policy/AdministratorAccess\n  Dummy:"
        )
        with pytest.raises(PClusterMakerError, match="not a valid EC2 instance type"):
            _validate_instance_types(payload, require_gpu=False)

    def test_colon_rejected(self):
        with pytest.raises(PClusterMakerError, match="not a valid EC2 instance type"):
            _validate_instance_types("c5.2xlarge:", require_gpu=False)

    def test_no_dot_rejected(self):
        with pytest.raises(PClusterMakerError, match="not a valid EC2 instance type"):
            _validate_instance_types("c5xlarge", require_gpu=False)

    def test_embedded_whitespace_rejected(self):
        with pytest.raises(PClusterMakerError, match="not a valid EC2 instance type"):
            _validate_instance_types("c5.2xlarge extra", require_gpu=False)

    def test_bare_metal_accepted(self):
        result = _validate_instance_types("c8g.metal", require_gpu=False)
        assert result == ["c8g.metal"]

    def test_hyphenated_metal_size_accepted(self):
        result = _validate_instance_types("c8g.metal-24xl", require_gpu=False)
        assert result == ["c8g.metal-24xl"]

    def test_all_catalog_metal_types_accepted(self):
        # Every metal-family instance type in the toolkit's own catalog must
        # validate — this is the exact class of real input an earlier,
        # narrower injection-hardening regex rejected.
        metal_types = [
            "c5.metal", "c5n.metal", "c6a.metal", "c6g.metal", "c6i.metal",
            "c7a.metal-48xl", "c7g.metal", "c7i.metal-24xl", "c7i.metal-48xl",
            "c8g.metal-24xl", "c8g.metal-48xl", "i3.metal", "i3en.metal",
            "i4i.metal", "m5.metal", "m5dn.metal", "m5zn.metal", "m6a.metal",
            "m6g.metal", "m6i.metal", "m7a.metal-48xl", "m7g.metal",
            "m7i.metal-24xl", "m7i.metal-48xl", "r5.metal", "r5dn.metal",
            "r6a.metal", "r6g.metal", "r6i.metal", "r7a.metal-48xl", "r7g.metal",
            "r7i.metal-24xl", "r7i.metal-48xl", "z1d.metal",
        ]
        for itype in metal_types:
            result = _validate_instance_types(itype, require_gpu=False)
            assert result == [itype], f"{itype} failed validation"

    def test_hyphenated_family_high_memory_types_accepted(self):
        # High Memory instances hyphenate the FAMILY, not the size
        # (u-6tb1.56xlarge) — the mirror-image case of metal-*'s hyphenated
        # size. A regex that only special-cased one side rejected the other.
        high_memory_types = [
            "u-6tb1.56xlarge", "u-9tb1.112xlarge", "u-12tb1.112xlarge",
            "u-18tb1.112xlarge", "u-24tb1.112xlarge",
        ]
        for itype in high_memory_types:
            result = _validate_instance_types(itype, require_gpu=False)
            assert result == [itype], f"{itype} failed validation"

    def test_entire_instance_catalog_accepted(self):
        # The regex must accept every single instance type the toolkit itself
        # considers valid, whatever hyphenation shape AWS uses for it. This
        # is the real invariant — enumerating specific hyphen positions
        # (metal-*, u-*tb1, or whatever AWS ships next) is the wrong strategy
        # and has already produced two rounds of asymmetric regressions.
        import pcluster_aux_data
        for itype in pcluster_aux_data.ec2_instances_full_list:
            require_gpu = pcluster_aux_data.is_gpu_instance(itype)
            result = _validate_instance_types(itype, require_gpu=require_gpu)
            assert result == [itype], f"{itype} failed validation"

    def test_trailing_hyphen_rejected(self):
        with pytest.raises(PClusterMakerError, match="not a valid EC2 instance type"):
            _validate_instance_types("c5.2xlarge-", require_gpu=False)


